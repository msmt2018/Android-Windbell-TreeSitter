/**
 * Dynamically creates and adds the grammar project modules to the build.
 *
 * @author Akash Yadav
 * @author android_zero <github.com/msmt2018> [update] : On October 31, 2026, fixed C++ JNI function naming collisions and aligned with combined headers.
 */
@Suppress("unused")
class DynamicModulePlugin : Plugin<Settings> {

  override fun apply(target: Settings) {
    target.run {
      val rootDir = target.rootDir
      val grammars = target.readGrammars()

      for (grammar in grammars) {
        val moduleDir = rootDir.resolve("grammar-modules/${grammar.name}")
          .also { it.mkdirs() }
        generateGrammarModule(grammar, moduleDir, rootDir)

        val moduleName = "tree-sitter-${grammar.name}"
        include(moduleName)
        project(":${moduleName}").projectDir = moduleDir
      }
    }
  }

  private fun generateGrammarModule(grammar: TsGrammar, moduleDir: File,
                                    rootDir: File
  ) {
    println("Generating module for grammar '${grammar.name}' (composite: ${grammar.composite})")
    writeBuildGradle(moduleDir)
    writeLangBinding(grammar, moduleDir)
    writeNative(grammar, moduleDir, rootDir)
  }

  private fun writeNative(grammar: TsGrammar, moduleDir: File, rootDir: File
  ) {
    val cppDir = File(moduleDir, "src/main/cpp/").also { it.mkdirs() }
    writeCmakeLists(grammar, cppDir, rootDir)
    writeJniImpl(grammar, cppDir)

    File(cppDir, ".gitignore").writeText("/host-build")
  }

  private fun writeJniImpl(grammar: TsGrammar, cppDir: File) {
    val file = File(cppDir, "tree-sitter-${grammar.name}.cpp")
    file.writeText(grammar.jniImplSrc().autoGenerated())
  }

  private fun writeCmakeLists(grammar: TsGrammar, cppDir: File, rootDir: File
  ) {
    val file = File(cppDir, "CMakeLists.txt")
    file.writeText(grammar.cmakeListsSrc(rootDir).autoGenerated(comment = "##"))
  }

  private fun writeLangBinding(grammar: TsGrammar, moduleDir: File) {
    val file = File(moduleDir,
      "src/main/java/com/zerostudio/idea/treesitter/${grammar.name}/TSLanguage${grammar.capitalizedName()}.java")
    file.parentFile.mkdirs()
    file.writeText(grammar.langBindingSrc().autoGenerated())
  }

  private fun writeBuildGradle(moduleDir: File) {
    val file = File(moduleDir, "build.gradle")
    file.writeText(buildGradleSrc().autoGenerated())
  }
}

private fun TsGrammar.jniImplSrc(): String {
  if (!composite) {
    val cEntry = entry ?: "tree_sitter_$name"
    return """
$LICENSE

#include <jni.h>
#include <tree_sitter/api.h>

#include "ts__onload.h"
#include "ts_${name}.h"

#ifdef __ANDROID__
static jint JNI_VERSION = JNI_VERSION_1_6;
#else
static jint JNI_VERSION = JNI_VERSION_10;
#endif

extern "C" TSLanguage *${cEntry}();

static jlong TSLanguage${capitalizedName()}_Native_getInstance_impl(JNIEnv *env, jclass clazz) {
    return (jlong) ${cEntry}();
}

void TSLanguage${capitalizedName()}_Native__SetJniMethods(JNINativeMethod *methods, int count) {
  SET_JNI_METHOD(methods, TSLanguage${capitalizedName()}_Native_getInstance, TSLanguage${capitalizedName()}_Native_getInstance_impl);
}

JNIEXPORT jint JNI_OnLoad(JavaVM *vm, void *reserved) {
  JNIEnv *env;
  if (vm->GetEnv(reinterpret_cast<void **>(&env), JNI_VERSION) != JNI_OK) {
    LOGE("AndroidTreeSitter", "Failed to get JNIEnv* from JavaVM: %p", vm);
    return JNI_ERR;
  }

  TS_JNI_ONLOAD__DEFINE_METHODS_ARR
  TS_JNI_ONLOAD__AUTO_REGISTER(env)

  return JNI_VERSION;
}
    """.trimIndent()
  }

  val subInits = subEntries.indices.joinToString("\n") { i ->
    val cEntry = if (i < subEntries.size) subEntries[i] else {
      val fallbackSub = subPaths[i].substringAfterLast('/')
      "tree_sitter_${fallbackSub.replace('-', '_')}"
    }
    """extern "C" TSLanguage *$cEntry();"""
  }

  // 为内部类生成独立的实现函数，加上 _impl 后缀，彻底解决与宏/变量名冲突问题
  val methodRegistrations = subPaths.indices.joinToString("\n\n") { i ->
    val path = subPaths[i]
    val cEntry = if (i < subEntries.size) subEntries[i] else {
      val fallbackSub = path.substringAfterLast('/')
      "tree_sitter_${fallbackSub.replace('-', '_')}"
    }
    val subFolderName = path.substringAfterLast('/')
    val capSubName = subFolderName.split(Regex("[-_]")).joinToString("") { it.replaceFirstChar { c -> c.titlecaseChar() } }
    
    """
static jlong TSLanguage${capitalizedName()}_TreeSitter${capSubName}Native_getInstance_impl(JNIEnv *env, jclass clazz) {
    return (jlong) $cEntry();
}

void TSLanguage${capitalizedName()}_TreeSitter${capSubName}Native__SetJniMethods(JNINativeMethod *methods, int count) {
  SET_JNI_METHOD(methods, TSLanguage${capitalizedName()}_TreeSitter${capSubName}Native_getInstance, TSLanguage${capitalizedName()}_TreeSitter${capSubName}Native_getInstance_impl);
}
    """.trimIndent()
  }

  return """
$LICENSE

#include <jni.h>
#include <tree_sitter/api.h>

#include "ts__onload.h"
#include "ts_${name}.h"

#ifdef __ANDROID__
static jint JNI_VERSION = JNI_VERSION_1_6;
#else
static jint JNI_VERSION = JNI_VERSION_10;
#endif

$subInits

$methodRegistrations

JNIEXPORT jint JNI_OnLoad(JavaVM *vm, void *reserved) {
  JNIEnv *env;
  if (vm->GetEnv(reinterpret_cast<void **>(&env), JNI_VERSION) != JNI_OK) {
    LOGE("AndroidTreeSitter", "Failed to get JNIEnv* from JavaVM: %p", vm);
    return JNI_ERR;
  }

  TS_JNI_ONLOAD__DEFINE_METHODS_ARR
  TS_JNI_ONLOAD__AUTO_REGISTER(env)

  return JNI_VERSION;
}
  """.trimIndent()
}

private fun TsGrammar.cmakeListsSrc(rootDir: File,
                                    grammarDir: File = File(rootDir,
                                      "grammars/$name")
): String {
  if (!grammarDir.exists()) {
    throw FileNotFoundException("Source directory for grammar '$name' not found")
  }

  if (!composite) {
    val sources = srcExtra.joinToString(
      separator = "\n        ") { "${grammarDir.absolutePath}/${it}" }
    return """
$CMAKE_LICENSE

cmake_minimum_required(VERSION 3.22.1)

project("tree-sitter-$name")

set(PROJECT_DIR ${rootDir.absolutePath})
include(${rootDir.absolutePath}/cmake/common-config.cmake)

set(CMAKE_C_FLAGS "${'$'}{CMAKE_C_FLAGS} -O3 -flto -fvisibility=hidden")
set(CMAKE_CXX_FLAGS "${'$'}{CMAKE_CXX_FLAGS} -O3 -flto -fvisibility=hidden")
set(CMAKE_SHARED_LINKER_FLAGS "${'$'}{CMAKE_SHARED_LINKER_FLAGS} -Wl,--gc-sections -s")

include_directories(${grammarDir.absolutePath}/src)

add_library(${'$'}{CMAKE_PROJECT_NAME} SHARED
        ${grammarDir.absolutePath}/src/parser.c
        $sources
        tree-sitter-${name}.cpp)
        
if (${'$'}{CMAKE_SYSTEM_NAME} STREQUAL Android)
    find_library(log log)
    target_link_libraries(tree-sitter-$name ${'$'}{log})
endif()
    """.trimIndent()
  }

  val sourceFiles = mutableListOf<String>()
  val includeDirs = mutableListOf<String>()

  subPaths.forEach { subPath ->
    val subDir = File(grammarDir, subPath)
    sourceFiles.add("${subDir.absolutePath}/src/parser.c")
    if (subDir.resolve("src/scanner.c").exists()) {
      sourceFiles.add("${subDir.absolutePath}/src/scanner.c")
    }
    if (subDir.resolve("src/scanner.cc").exists()) {
      sourceFiles.add("${subDir.absolutePath}/src/scanner.cc")
    }
    includeDirs.add("${subDir.absolutePath}/src")
  }

  srcExtra.forEach { extra ->
    sourceFiles.add("${grammarDir.absolutePath}/$extra")
  }

  val sourcesStr = sourceFiles.joinToString(separator = "\n        ")
  val includesStr = includeDirs.joinToString(separator = "\n        ") { "include_directories($it)" }

  return """
$CMAKE_LICENSE

cmake_minimum_required(VERSION 3.22.1)

project("tree-sitter-$name")

set(PROJECT_DIR ${rootDir.absolutePath})
include(${rootDir.absolutePath}/cmake/common-config.cmake)

set(CMAKE_C_FLAGS "${'$'}{CMAKE_C_FLAGS} -O3 -flto -fvisibility=hidden")
set(CMAKE_CXX_FLAGS "${'$'}{CMAKE_CXX_FLAGS} -O3 -flto -fvisibility=hidden")
set(CMAKE_SHARED_LINKER_FLAGS "${'$'}{CMAKE_SHARED_LINKER_FLAGS} -Wl,--gc-sections -s")

$includesStr

add_library(${'$'}{CMAKE_PROJECT_NAME} SHARED
        $sourcesStr
        tree-sitter-${name}.cpp)
        
if (${'$'}{CMAKE_SYSTEM_NAME} STREQUAL Android)
    find_library(log log)
    target_link_libraries(tree-sitter-$name ${'$'}{log})
endif()
  """.trimIndent()
}

private fun TsGrammar.langBindingSrc(): String {
  if (!composite) {
    return """
$LICENSE

package com.zerostudio.idea.treesitter.$name;

import com.zerostudio.idea.treesitter.annotations.GenerateNativeHeaders;
import com.zerostudio.idea.treesitter.TSLanguage;
import com.zerostudio.idea.treesitter.TSLanguageCache;

public final class TSLanguage${capitalizedName()} {

  static {
    System.loadLibrary("tree-sitter-$name");
  }

  private TSLanguage${capitalizedName()}() {
    throw new UnsupportedOperationException();
  }

  @Deprecated
  public static TSLanguage newInstance() {
    return getInstance();
  }
  
  public static TSLanguage getInstance() {
    var language = TSLanguageCache.get("$name");
    if (language != null) {
      return language;
    }

    language = TSLanguage.create("$name", Native.getInstance());
    TSLanguageCache.cache("$name", language);
    return language;
  }

  @GenerateNativeHeaders(fileName = "$name")
  public static class Native {
    public static native long getInstance();
  }
}
    """.trimIndent()
  }

  val primaryPath = subPaths.firstOrNull() ?: ""
  val primarySubName = primaryPath.substringAfterLast('/')
  val primaryCapName = primarySubName.split(Regex("[-_]")).joinToString("") { it.replaceFirstChar { c -> c.titlecaseChar() } }

  val innerClasses = subPaths.indices.joinToString("\n\n") { i ->
    val path = subPaths[i]
    val subName = path.substringAfterLast('/')
    val cacheKey = subName
    val capSubName = subName.split(Regex("[-_]")).joinToString("") { it.replaceFirstChar { c -> c.titlecaseChar() } }
    """
  public static TSLanguage get${capSubName}Instance() {
    var language = TSLanguageCache.get("$cacheKey");
    if (language != null) {
      return language;
    }

    language = TSLanguage.create("$cacheKey", TreeSitter${capSubName}Native.getInstance());
    TSLanguageCache.cache("$cacheKey", language);
    return language;
  }

  @GenerateNativeHeaders(fileName = "$name")
  public static class TreeSitter${capSubName}Native {
    public static native long getInstance();
  }
    """.trimIndent()
  }

  return """
$LICENSE

package com.zerostudio.idea.treesitter.$name;

import com.zerostudio.idea.treesitter.annotations.GenerateNativeHeaders;
import com.zerostudio.idea.treesitter.TSLanguage;
import com.zerostudio.idea.treesitter.TSLanguageCache;

/**
 * Composite Tree Sitter for ${capitalizedName()}.
 *
 * @author android_zero <github.com/msmt2018>
 */
public final class TSLanguage${capitalizedName()} {

  static {
    System.loadLibrary("tree-sitter-$name");
  }

  private TSLanguage${capitalizedName()}() {
    throw new UnsupportedOperationException();
  }

  public static TSLanguage getInstance() {
    return get${primaryCapName}Instance();
  }

  public static void preloadAll() {
    ${subPaths.joinToString("\n    ") { p ->
        val sName = p.substringAfterLast('/')
        val cName = sName.split(Regex("[-_]")).joinToString("") { it.replaceFirstChar { c -> c.titlecaseChar() } }
        "get${cName}Instance();"
    }}
  }

$innerClasses
}
  """.trimIndent()
}

